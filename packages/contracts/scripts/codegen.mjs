function define(name, schema) {
  if (Object.hasOwn(definitions, name)) throw new Error('Duplicate schema ' + name);
  definitions[name] = schema;
  return ref(name);
}

for (const [tool, { name, module, input, output }] of tools) {
  if (!definitions.ModuleId.enum.includes(module)) throw new Error('Unknown module ' + module);
  const request = define(
    name + 'Request',
    object({
      envelope: ref('CallEnvelope'),
      tool: enumeration(tool),
      input: define(name + 'Input', input),
    }),
  );
  const success = define(
    name + 'Ok',
    object({ state: enumeration('ok'), output: define(name + 'Output', output) }),
  );
  requests.push(request);
  results.push(define(name + 'Result', union(success, ...failures)));
}
define('ToolName', enumeration(...Object.keys(catalog)));
define('ToolCall', union(...requests));
define('ToolResult', union(...results));

function refName(reference) {
  const match = /^#\/\$defs\/([A-Z][A-Za-z0-9]*)$/.exec(reference);
  if (!match || !Object.hasOwn(definitions, match[1]))
    throw new Error('Unknown reference ' + reference);
  return match[1];
}

// This catalog uses a finite JSON Schema subset. Reject extensions until both bindings support them.
function assertSupported(schema) {
  const shapes = {
    object: ['type', 'additionalProperties', 'properties', 'required'],
    array: ['type', 'items'],
    string: ['type', 'minLength', 'pattern'],
    number: ['type', 'minimum', 'maximum'],
    integer: ['type', 'minimum', 'maximum'],
    boolean: ['type'],
    null: ['type'],
  };
  const allowed = schema.$ref
    ? ['$ref']
    : schema.enum
      ? ['enum']
      : schema.anyOf
        ? ['anyOf']
        : shapes[schema.type];
  if (!allowed || Object.keys(schema).some((key) => !allowed.includes(key))) {
    throw new Error('Unsupported schema ' + JSON.stringify(schema));
  }
  if (
    schema.type === 'object' &&
    (schema.additionalProperties !== false ||
      schema.required.some((key) => !Object.hasOwn(schema.properties, key)))
  ) {
    throw new Error('Objects must be closed and required fields must be declared');
  }
  if (schema.$ref) refName(schema.$ref);
  if (
    schema.enum &&
    (!schema.enum.length ||
      schema.enum.some((value) => !['string', 'boolean'].includes(typeof value)))
  ) {
    throw new Error('Enumerations must contain strings or booleans');
  }
  if (schema.type === 'object') Object.values(schema.properties).forEach(assertSupported);
  if (schema.items) assertSupported(schema.items);
  if (schema.anyOf) schema.anyOf.forEach(assertSupported);
}
for (const [name, schema] of Object.entries(definitions)) {
  if (!/^[A-Z][A-Za-z0-9]*$/.test(name)) throw new Error('Invalid schema name ' + name);
  assertSupported(schema);
}

function typeScript(schema, level = 0) {
  if (schema.$ref) return refName(schema.$ref);
  if (schema.enum) return schema.enum.map((value) => JSON.stringify(value)).join(' | ');
  if (schema.anyOf) return schema.anyOf.map((item) => typeScript(item, level)).join(' | ');
  if (schema.type === 'integer') return 'number';
  if (schema.type === 'array') return 'Array<' + typeScript(schema.items, level) + '>';
  if (schema.type !== 'object') return schema.type;
  const pad = '  '.repeat(level);
  const fields = Object.entries(schema.properties).map(
    ([key, field]) =>
      pad +
      '  ' +
      JSON.stringify(key) +
      (schema.required.includes(key) ? ': ' : '?: ') +
      typeScript(field, level + 1) +
      ';',
  );
  return ['{', ...fields, pad + '}'].join('\n');
}

