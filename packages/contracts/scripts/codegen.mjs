function emit(path, contents) {
  const file = new URL(path, base);
  if (!check) {
    writeFileSync(file, contents);
    return;
  }
  let actual;
  try {
    actual = readFileSync(file, 'utf8').replaceAll('\r\n', '\n');
  } catch (error) {
    if (error.code !== 'ENOENT') throw error;
  }
  if (actual !== contents) {
    console.error(path + ' is stale. Run pnpm codegen.');
    process.exitCode = 1;
  }
}

