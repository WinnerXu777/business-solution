const emitted = new Set();
const visiting = new Set();
const constraints = { minimum: 'ge', maximum: 'le', minLength: 'min_length', pattern: 'pattern' };

function emitPython(name, schema) {
  if (emitted.has(name)) return;
  if (visiting.has(name)) throw new Error('Recursive or overlapping Python type ' + name);
  visiting.add(name);
  if (schema.type === 'object') {
    const fields = Object.entries(schema.properties).map(([key, field]) => {
      if (!/^[a-z][A-Za-z0-9]*$/.test(key)) throw new Error('Invalid Python field ' + key);
      const type = pythonType(field, name + key[0].toUpperCase() + key.slice(1));
      return '    ' + key + ': ' + type + (schema.required.includes(key) ? '' : ' = None');
    });
    py.push(
      '',
      '',
      'class ' + name + '(ContractModel):',
      ...(fields.length ? fields : ['    pass']),
    );
  } else {
    const type = pythonType(schema, name);
    py.push('', '', name + ': TypeAlias = ' + type);
  }
  visiting.delete(name);
  emitted.add(name);
}

function pythonType(schema, nestedName) {
  if (schema.$ref) {
    const target = refName(schema.$ref);
    emitPython(target, definitions[target]);
    return target;
  }
  if (schema.type === 'object') {
    if (Object.hasOwn(definitions, nestedName) || emitted.has(nestedName)) {
      throw new Error('Duplicate nested Python definition ' + nestedName);
    }
    emitPython(nestedName, schema);
    return nestedName;
  }
  if (schema.enum) {
    const values = schema.enum.map((value) =>
      typeof value === 'boolean' ? (value ? 'True' : 'False') : JSON.stringify(value),
    );
    return 'Literal[' + values.join(', ') + ']';
  }
  if (schema.anyOf) {
    return schema.anyOf
      .map((arm, index) => pythonType(arm, nestedName + 'Variant' + (index + 1)))
      .join(' | ');
  }
  if (schema.type === 'array') return 'list[' + pythonType(schema.items, nestedName + 'Item') + ']';
  const type = { boolean: 'bool', integer: 'int', number: 'float', null: 'None', string: 'str' }[
    schema.type
  ];
  const argumentsList = Object.entries(constraints)
    .filter(([key]) => Object.hasOwn(schema, key))
    .map(([key, argument]) => argument + '=' + JSON.stringify(schema[key]));
  return argumentsList.length
    ? 'Annotated[' + type + ', Field(' + argumentsList.join(', ') + ')]'
    : type;
}

for (const [name, schema] of Object.entries(definitions)) emitPython(name, schema);

const openRef = (name) => ({ $ref: '#/components/schemas/' + name });
function openSchema(schema) {
  if (schema.$ref) return openRef(refName(schema.$ref));
  if (schema.type === 'object') {
    return {
      ...schema,
      properties: Object.fromEntries(
        Object.entries(schema.properties).map(([key, child]) => [key, openSchema(child)]),
      ),
    };
  }
  if (schema.type === 'array') return { ...schema, items: openSchema(schema.items) };
  if (schema.anyOf) return { anyOf: schema.anyOf.map(openSchema) };
  return schema;
}
